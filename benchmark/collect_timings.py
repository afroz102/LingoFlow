#!/usr/bin/env python3
"""Aggregate raw benchmark runs into the Gate 1 latency report (VALIDATION_PLAN.md 3.4).

Input is the `latency_runs.jsonl` produced on-device by
`app/src/androidTest/.../TranslationLatencyBenchmark.kt` and pulled with adb --
see benchmark/TIMING_HARNESS.md for the full procedure.

Usage:
    python3 benchmark/collect_timings.py latency_runs.jsonl
    python3 benchmark/collect_timings.py latency_runs.jsonl --report benchmark/latency_report.md

3.4 forbids averaging the four directions into one number, so every table here is sliced by
direction and length bucket and no overall latency figure is printed anywhere.
"""

import argparse
import json
import sys
from collections import defaultdict

NANOS_PER_MILLI = 1_000_000

# Derived intervals from VALIDATION_PLAN.md 3.4 that this harness can actually compute,
# as (report name, start mark, end mark).
DERIVED_INTERVALS = [
    ("platform_entry", "T_ACTION", "T_RECEIVE"),
    ("direction", "T_RECEIVE", "T_DIRECTION"),
    ("client_readiness", "T_DIRECTION", "T_CLIENT_READY"),
    ("request_setup", "T_CLIENT_READY", "T_REQUEST_SENT"),
    ("provider_round_trip", "T_REQUEST_SENT", "T_RESPONSE_END"),
    ("render", "T_RESPONSE_END", "T_RENDER"),
    ("end_to_end", "T_ACTION", "T_RENDER"),
]

# 3.4 intervals this harness cannot compute, and why. Printed in the report rather than
# omitted, so a reader is never left assuming the whole 3.4 chain was measured.
UNAVAILABLE_INTERVALS = {
    "attestation (T_attested - T_client_ready)":
        "The Firebase AI Logic SDK does not expose the App Check token used by a specific "
        "generateContent call, so there is no attestation-ready instant to mark.",
    "provider_first_output (T_first_output - T_request_sent)":
        "Needs a streaming response. GeminiTranslationProvider uses non-streaming "
        "generateContent, so no first-token event exists. 3.4 itself scopes this to "
        "'when exposed by the SDK'.",
    "completion (T_response_end - T_first_output)":
        "Depends on T_first_output above.",
}

# VALIDATION_PLAN.md 3.6. Checked only where this harness measures the same thing; the
# network profile is not something the script can verify, so the Wi-Fi condition is stated
# rather than enforced.
END_TO_END_P50_BUDGET_MS = 1000
END_TO_END_P95_BUDGET_MS = 2000
BUDGET_BUCKETS = {"words_1_3", "chars_le_50", "chars_le_200"}


def percentile(sorted_values, fraction):
    """Nearest-rank percentile.

    Deliberately not interpolated: with the 30-100 runs per slice that 3.4 asks for,
    interpolation invents values between two real measurements, and a P99 that never
    actually happened is a bad thing to hold a release gate against.
    """
    if not sorted_values:
        return None
    rank = max(1, -(-len(sorted_values) * fraction // 1))  # ceil, integer arithmetic
    return sorted_values[int(rank) - 1]


def summarise(values_ms):
    values = sorted(values_ms)
    return {
        "n": len(values),
        "min": values[0],
        "p50": percentile(values, 0.50),
        "p95": percentile(values, 0.95),
        "p99": percentile(values, 0.99),
        "max": values[-1],
    }


def load_runs(path):
    runs, errors = [], []
    with open(path, encoding="utf-8") as handle:
        for lineno, line in enumerate(handle, 1):
            if not line.strip():
                continue
            try:
                runs.append(json.loads(line))
            except json.JSONDecodeError as exc:
                errors.append(f"{path}:{lineno}: not valid JSON: {exc}")
    return runs, errors


def intervals_for(run):
    """Milliseconds per derived interval for one run, skipping any whose marks are absent.

    A mark can legitimately be missing -- a run that failed offline never reaches
    T_RESPONSE_END -- so a missing mark drops that one interval rather than the whole run.
    """
    marks = dict(run.get("marks") or {})
    if "T_ACTION" in run:
        marks["T_ACTION"] = run["T_ACTION"]

    result = {}
    for name, start, end in DERIVED_INTERVALS:
        if start in marks and end in marks:
            delta = marks[end] - marks[start]
            # A negative interval means the marks are out of order, which would be a real
            # instrumentation defect. Surfacing it beats silently reporting a negative P50.
            if delta < 0:
                raise ValueError(
                    f"run {run.get('item_id')}: {end} is earlier than {start} "
                    f"({delta} ns). The timing chain is mis-instrumented; fix it before "
                    "trusting any number in this report."
                )
            result[name] = delta / NANOS_PER_MILLI
    return result


def build_report(runs):
    lines = ["# Gate 1 latency report", ""]
    lines.append("Generated by `benchmark/collect_timings.py` from on-device runs.")
    lines.append("Timing definitions: [VALIDATION_PLAN.md §3.4](../docs/VALIDATION_PLAN.md#34-timing-definitions).")
    lines.append("")
    lines.append(f"**Total runs recorded: {len(runs)}**")
    lines.append("")

    outcomes = defaultdict(int)
    for run in runs:
        outcomes[run.get("outcome", "UNKNOWN")] += 1
    lines.append("## Outcomes")
    lines.append("")
    lines.append("§3.4 requires provider failures and quota consumption to be reported, not just")
    lines.append("successful latencies. Failed runs are counted here and excluded from the")
    lines.append("latency tables below, which describe successful requests only.")
    lines.append("")
    lines.append("| Outcome | Runs |")
    lines.append("|---|---:|")
    for outcome, count in sorted(outcomes.items(), key=lambda kv: -kv[1]):
        lines.append(f"| `{outcome}` | {count} |")
    lines.append("")

    successful = [r for r in runs if r.get("outcome") == "SUCCESS"]

    by_slice = defaultdict(lambda: defaultdict(list))
    for run in successful:
        key = (run.get("direction", "?"), run.get("length_bucket", "?"))
        for name, value in intervals_for(run).items():
            by_slice[key][name].append(value)

    lines.append("## End-to-end latency by direction and length")
    lines.append("")
    lines.append("§3.4: the four directions are never averaged together. All values in milliseconds.")
    lines.append("")
    lines.append("| Direction | Length bucket | n | min | P50 | P95 | P99 | max | §3.6 |")
    lines.append("|---|---|---:|---:|---:|---:|---:|---:|---|")
    for (direction, bucket) in sorted(by_slice):
        values = by_slice[(direction, bucket)].get("end_to_end")
        if not values:
            continue
        s = summarise(values)
        if bucket in BUDGET_BUCKETS:
            within = s["p50"] <= END_TO_END_P50_BUDGET_MS and s["p95"] <= END_TO_END_P95_BUDGET_MS
            verdict = "within" if within else "**OVER**"
        else:
            verdict = "n/a"
        lines.append(
            f"| `{direction}` | `{bucket}` | {s['n']} | {s['min']:.0f} | {s['p50']:.0f} | "
            f"{s['p95']:.0f} | {s['p99']:.0f} | {s['max']:.0f} | {verdict} |"
        )
    lines.append("")
    lines.append(f"§3.6 budget applied: P50 ≤ {END_TO_END_P50_BUDGET_MS} ms and "
                 f"P95 ≤ {END_TO_END_P95_BUDGET_MS} ms, for selections up to 200 characters on "
                 "stable reference Wi-Fi. **The script cannot verify which network the run used** — "
                 "confirm the network profile from the run log before treating a `within` as a pass.")
    lines.append("")

    lines.append("## Stage breakdown")
    lines.append("")
    lines.append("Where the end-to-end time actually goes, per direction. All values in milliseconds.")
    lines.append("")
    for (direction, bucket) in sorted(by_slice):
        stages = by_slice[(direction, bucket)]
        lines.append(f"### `{direction}` / `{bucket}`")
        lines.append("")
        lines.append("| Interval | n | min | P50 | P95 | P99 | max |")
        lines.append("|---|---:|---:|---:|---:|---:|---:|")
        for name, _, _ in DERIVED_INTERVALS:
            values = stages.get(name)
            if not values:
                continue
            s = summarise(values)
            lines.append(
                f"| `{name}` | {s['n']} | {s['min']:.1f} | {s['p50']:.1f} | {s['p95']:.1f} | "
                f"{s['p99']:.1f} | {s['max']:.1f} |"
            )
        lines.append("")

    lines.append("## Not measured")
    lines.append("")
    lines.append("These §3.4 intervals are absent by cause, not by oversight. Any Gate 1 decision")
    lines.append("record must state that they were not measured.")
    lines.append("")
    for name, reason in UNAVAILABLE_INTERVALS.items():
        lines.append(f"- **{name}** — {reason}")
    lines.append("")

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("runs", help="latency_runs.jsonl pulled from the device")
    parser.add_argument("--report", help="write the markdown report to this path")
    args = parser.parse_args()

    try:
        runs, errors = load_runs(args.runs)
    except FileNotFoundError:
        print(f"FAIL: no run file at {args.runs}", file=sys.stderr)
        return 2

    if errors:
        print(f"FAIL: {len(errors)} malformed line(s):", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1

    if not runs:
        print(f"FAIL: {args.runs} contains no runs", file=sys.stderr)
        return 1

    try:
        report = build_report(runs)
    except ValueError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1

    successful = sum(1 for r in runs if r.get("outcome") == "SUCCESS")
    print(f"OK: {len(runs)} runs ({successful} successful, {len(runs) - successful} failed)")

    if args.report:
        with open(args.report, "w", encoding="utf-8") as handle:
            handle.write(report)
        print(f"  report written to {args.report}")
    else:
        print()
        print(report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
